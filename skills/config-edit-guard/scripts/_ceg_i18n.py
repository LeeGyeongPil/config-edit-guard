MESSAGES: Mapping[str, Mapping[str, str]] = {"en": EN, "ko": KO}


def resolve_lang(cli_value: Optional[str], environ: Optional[Mapping[str, str]] = None) -> str:
    """--lang, then CONFIG_EDIT_GUARD_LANG, LC_ALL, LC_MESSAGES, LANG; anything not starting with ko is English."""
    env = os.environ if environ is None else environ
    for value in (cli_value, env.get(ENV_NAME), env.get("LC_ALL"), env.get("LC_MESSAGES"), env.get("LANG")):
        if value and value.strip():
            return "ko" if value.strip().lower().startswith("ko") else "en"
    return "en"


def t(lang: str, key: str, /, **params) -> str:
    table = MESSAGES.get(lang, EN)
    text = table.get(key) or EN[key]
    return text.format(**params) if params else text.replace("{{", "{").replace("}}", "}")


def _format_params(lang: str, params: Mapping[str, object]) -> dict:
    out: dict = dict(params)
    out.setdefault("file", "<input>")
    for name, value in list(out.items()):
        if name.endswith("_lines") and isinstance(value, list):
            out[name] = ", ".join(t(lang, "word.line", n=n) for n in value)
    return out


def error_line(lang: str, err: ConfigError) -> str:
    params = _format_params(lang, err.params)
    message = t(lang, err.key, **params)
    hint = t(lang, err.key + ".fix", **params)
    return t(lang, "frame.error", code=err.code, message=message, hint=hint)


# ---------------------------------------------------------------- argparse in two languages

_ARG_RULES = [
    (re.compile(r"^the following arguments are required: (.+)$"), "argerr.required", ("names",)),
    (re.compile(r"^unrecognized arguments: (.+)$"), "argerr.unrecognized", ("names",)),
    (re.compile(r"^argument (.+?): invalid choice: (.+?) \(choose from (.+)\)$"), "argerr.invalid_choice", ("name", "value", "choices")),
    (re.compile(r"^argument (.+?): expected one argument$"), "argerr.expected_one", ("name",)),
    (re.compile(r"^argument (.+?): invalid (\w+) value: (.+)$"), "argerr.invalid_value", ("name", "kind", "value")),
]


def translate_argparse_error(lang: str, message: str) -> str:
    for pattern, key, names in _ARG_RULES:
        m = pattern.match(message)
        if m:
            return t(lang, key, **dict(zip(names, m.groups())))
    return t(lang, "argerr.other", detail=message)


def make_parser_class(lang: str):
    """ArgumentParser subclass whose labels, help line and errors follow ``lang``."""

    class _Formatter(argparse.HelpFormatter):
        def add_usage(self, usage, actions, groups, prefix=None):
            if prefix is None:
                prefix = t(lang, "label.usage") + " "
            super().add_usage(usage, actions, groups, prefix)

    class _Parser(argparse.ArgumentParser):
        def __init__(self, *args, **kwargs):
            kwargs.setdefault("formatter_class", _Formatter)
            kwargs["add_help"] = False
            try:
                super().__init__(*args, color=False, **kwargs)
            except TypeError:
                super().__init__(*args, **kwargs)
            self._positionals.title = t(lang, "label.positionals")
            self._optionals.title = t(lang, "label.options")
            self.add_argument("-h", "--help", action="help", help=t(lang, "help.help"))

        def error(self, message):
            raise ConfigError("E_USAGE", "e.usage.args", detail=translate_argparse_error(lang, message))

    return _Parser


def error_parts(lang: str, err: ConfigError) -> tuple:
    """(message, fix hint) of an error in the chosen language."""
    params = _format_params(lang, err.params)
    return t(lang, err.key, **params), t(lang, err.key + ".fix", **params)
